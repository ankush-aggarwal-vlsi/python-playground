x = int(input("ENTER THE FIRST NUMBER : "))
y = int(input("ENTER THE SECOND NUMBER : "))
if x > y :
    print("THE LARGEST OUT OF TWO NUMBERS WILL BE :",x)
elif x < y :
    print("THE LARGEST OUT OF TWO NUMBERS WILL BE :",y)
else :
    print("BOTH THE NUMBERS ARE SAME")
    